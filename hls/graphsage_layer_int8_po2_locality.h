// ============================================================================
// Power-of-Two Scale Shift Amounts
// ============================================================================
// 
// These replace arbitrary scale values with shift amounts.
// Formula: shift = M_BITS - log2(scale_po2)
//
// Example: If eff_scale_float = 0.0106867758
//          eff_scale_fp = 0.0106867758 * 2^24 = 179,294
//          Nearest PO2 = 2^17 = 131,072
