/**
 * GraphSAGE Layer for FPGA - INT8 with POWER-OF-TWO SCALES
 * 
 * OPTIMIZED VERSION: PO2 scales + latency-preserving internal-locality experiment.
 *
 * LOCALITY MODE (default enabled):
 *   - No DATAFLOW
 *   - No intentional extra pipeline stage
 *   - AGG1 outputs are replicated at the producer boundary for LIN1 groups
 *   - LIN1+ReLU outputs are replicated at the producer boundary for AGG2 node groups
 *   - Designed to reduce long activation-register -> DSP routes
 * This eliminates the ~500-700 DSP48s used for scale multiplications.
 * 
 * Key differences from graphsage_layer_int8.h:
 *   - Scale values are constrained to powers of 2
 *   - Scale multiplication replaced with bit-shift
 *   - Shorter critical path → better timing
 *   - Lower DSP usage
 * 
 * Usage:
 *   1. Generate PO2 parameters: python prepare_ptq_int8_parameters.py --po2-scales
 *   2. Compile with: -DUSE_PO2_SCALES
 *   3. Optionally enable optimized bitwidths: -DUSE_OPTIMIZED_BITWIDTHS
 */

