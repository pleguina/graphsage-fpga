// ============================================================================
// Internal locality experiment
// ============================================================================
//
// Goal:
//   Preserve the latency-first architecture (II=1 / no intentional new
//   pipeline stage) while breaking global activation-to-DSP broadcast domains.
//
// DSE_ENABLE_INTERNAL_LOCALITY = 1:
//   - AGG1 produces multiple same-stage copies, one per LIN1 output group.
//   - LIN1 consumes those local copies and directly produces multiple ReLU'd
//     hidden copies, one per AGG2 destination-node group.
//   - AGG2 consumes the hidden copy associated with its destination-node group.
//   - No DATAFLOW is used.
//   - No extra copy loop exists as a separate pipeline stage.
//
// IMPORTANT:
//   HLS/Vivado must still be checked to confirm that the copies survive
//   synthesis as independent registers and that cycle latency/II are unchanged.
//
#ifndef DSE_ENABLE_INTERNAL_LOCALITY
#define DSE_ENABLE_INTERNAL_LOCALITY 1
#endif

